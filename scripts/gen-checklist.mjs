#!/usr/bin/env node
/** Regenerates api-coverage-checklist.md from the registry + operations.json. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { buildRegistry } = await import(path.join(root, "build/registry.js"));
const { shapeKey } = await import(path.join(root, "build/naming.js"));
const opsFile = JSON.parse(fs.readFileSync(path.join(root, "src/generated/operations.json"), "utf8"));
const reg = buildRegistry(null);
const toolByShape = new Map(reg.tools.map((t) => [shapeKey(t.op.method, t.op.path), t]));
const skipByShape = new Map(reg.skipped.map((s) => [shapeKey(...s.key.split(/ (.*)/s).slice(0, 2)), s]));
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 160);
const rows = [];
for (const op of opsFile.operations) {
  const k = shapeKey(op.method, op.path);
  const t = toolByShape.get(k);
  const sk = skipByShape.get(k);
  const flags = [op.legacyFallback ? "legacy fallback (gone from live v3 docs)" : "", op.deprecated ? "deprecated" : "", sk ? `exception: ${sk.reason}` : ""].filter(Boolean).join("; ");
  rows.push(`| ${sk ? "[E]" : "[x]"} | \`${t?.name ?? sk?.name ?? ""}\` | ${op.specFile} | ${esc(op.operationId)} | \`${op.method} ${esc(op.path)}\` | ${op.versionHeader || "(none)"} | ${esc(flags)} |`);
}
const out = `# API coverage checklist

Generated by \`npm run checklist\` from \`src/generated/operations.json\` (${opsFile.generatedAt}) and the live registry.

**${opsFile.operations.length} unique operations** (${opsFile.totals.rawOperations} raw across legacy + v3 spec tiers; v3 canonical where both exist). **${reg.tools.length} tools registered**, ${reg.skipped.length} explicit exceptions. Legend: \`[x]\` implemented · \`[E]\` exception (not registered, reason given).

| Status | Tool | Spec | operationId | Endpoint | Version | Notes |
|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
fs.writeFileSync(path.join(root, "api-coverage-checklist.md"), out);
console.log(`checklist: ${rows.length} rows`);
